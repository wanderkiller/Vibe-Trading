#!/usr/bin/env python3
"""Machine acceptance of an IR research session (research-truth spec §8). Read-only.

    python scripts/alphakeel_replay_check.py <session_id> [--sessions-dir DIR] [--runs-dir DIR] [--hypotheses FILE]

Run inside the Vibe-Trading container (or anywhere the session's trace, its run directory and the ``ir backtest`` run
directories are at the paths the trace names). Prints one ``PASS`` / ``FAIL`` line per check and exits 1 when any fails:

1. no ``ir_backtest`` failed on a request error (``request.invalid``, ``resource.rows``, ``step_minutes``, ``base/quote``)
2. at most one ``ir_validate`` failed on the IR's structure
3. every successful ``ir_backtest`` has ``evidence_dir``, and its run card's ``trials.count`` is the number of versions
   (distinct ``strategy_id``) in the ledger at that time
4. the final answer ends with the result card, its header counts N versions (distinct ``strategy_id``) / M backtests as
   the ledger does, and every number in the card's table is a registered ``metrics`` value (as the card prints it:
   2 decimals, the drawdown as a percent)
5. no ``answer_rejected`` issue points at a registered number under ``ir_runs/``
6. no separate ``freeze`` call
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Any

AGENT = Path(__file__).resolve().parents[1] / "agent"
if str(AGENT) not in sys.path:
    sys.path.insert(0, str(AGENT))

PARAM_ERROR_TOKENS = ("request.invalid", "resource.rows", "step_minutes", "base/quote")
STRUCTURE_CODES = ("ir.shape", "ir.invalid")
CARD_TITLES = ("**研究结果（系统根据试验账本生成，非模型撰写）**",
               "**Research result (generated by the system from the trial ledger, not written by the model)**")
CARD_LAST = ("账本：", "Ledger: ")


def _default_root() -> Path:
    try:
        from src.config.paths import get_runtime_root

        return Path(get_runtime_root())
    except Exception:  # noqa: BLE001 - standalone
        import os

        home = os.environ.get("VIBE_TRADING_HOME")
        return Path(home).expanduser() if home else Path.home() / ".vibe-trading"


def _text(entry: dict, trace_dir: Path, field: str) -> str:
    """A trace entry's text field, inline or from its sidecar (``<field>_path``)."""
    if isinstance(entry.get(field), str):
        return entry[field]
    rel = entry.get(f"{field}_path")
    if rel:
        try:
            return (trace_dir / rel).read_text(encoding="utf-8")
        except OSError:
            pass
    return str(entry.get(f"{field}_preview") or entry.get("preview") or "")


def _json(text: str) -> Any:
    try:
        return json.loads(text)
    except (ValueError, TypeError):
        return None


def load_trace(trace_dir: Path) -> list[dict]:
    out = []
    with open(trace_dir / "trace.jsonl", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                doc = _json(line)
                if isinstance(doc, dict):
                    out.append(doc)
    return out


def research_calls(entries: list[dict], trace_dir: Path) -> list[dict]:
    """``alphakeel_research`` calls in order: ``{call_id, action, args, status, payload, text}``."""
    calls: dict[str, dict] = {}
    order: list[str] = []
    for e in entries:
        if e.get("tool") != "alphakeel_research" or not e.get("call_id"):
            continue
        cid = e["call_id"]
        if e.get("type") == "tool_call":
            args = e.get("args") or {}
            calls[cid] = {"call_id": cid, "action": str(args.get("action") or ""), "args": args, "status": None,
                          "payload": None, "text": ""}
            order.append(cid)
        elif e.get("type") == "tool_result" and cid in calls:
            text = _text(e, trace_dir, "result")
            calls[cid].update(status=e.get("status"), text=text, payload=_json(text))
    return [calls[c] for c in order]


def _failed(call: dict) -> bool:
    p = call["payload"]
    return call["status"] == "error" or (isinstance(p, dict) and p.get("status") == "error")


def _ok(call: dict) -> bool:
    p = call["payload"]
    return isinstance(p, dict) and p.get("status") == "ok" and call["status"] != "error"


def session_run_dir(calls: list[dict], session_id: str, runs_dir: Path) -> Path | None:
    for c in calls:
        rd = (c["args"] or {}).get("run_dir")
        if isinstance(rd, str) and rd and Path(rd).is_dir():
            return Path(rd)
    found = []
    for req in runs_dir.glob("*/req.json"):
        doc = _json(req.read_text(encoding="utf-8", errors="replace"))
        if isinstance(doc, dict) and (doc.get("context") or {}).get("session_id") == session_id:
            found.append(req.parent)
    return sorted(found)[-1] if found else None


def registered(session_dir: Path | None, hypotheses: Path | None) -> list[dict]:
    """The session hypothesis' linked runs (read-only)."""
    if session_dir is None:
        return []
    hid = (_json((session_dir / "ir_hypothesis.json").read_text(encoding="utf-8"))
           if (session_dir / "ir_hypothesis.json").is_file() else None) or {}
    hid = hid.get("hypothesis_id")
    if not hid:
        return []
    if hypotheses is None:
        from src.hypotheses.registry import default_hypotheses_path

        hypotheses = default_hypotheses_path()
    doc = _json(Path(hypotheses).read_text(encoding="utf-8")) if Path(hypotheses).is_file() else None
    for h in doc or []:
        if isinstance(h, dict) and h.get("hypothesis_id") == hid:
            return [rc for rc in h.get("run_cards") or [] if isinstance(rc, dict)]
    return []


def final_answer(entries: list[dict], trace_dir: Path) -> str | None:
    answers = [e for e in entries if e.get("type") == "answer"]
    return _text(answers[-1], trace_dir, "content") if answers else None


def _dec(v: Any) -> Decimal | None:
    try:
        d = Decimal(str(v).replace("−", "-").replace(",", "").rstrip("%"))
    except (InvalidOperation, ValueError):
        return None
    return d if d.is_finite() else None


def _matches(written: str, value: Any) -> bool:
    """``written`` (a prose figure) is ``value`` rounded to the decimals written."""
    w, v = _dec(written), _dec(value)
    if w is None or v is None:
        return False
    places = -w.as_tuple().exponent if w.as_tuple().exponent < 0 else 0
    return abs(w - v) <= Decimal(1).scaleb(-places) / 2


# --- checks ------------------------------------------------------------------------------------------------------------

def check_1(calls: list[dict]) -> tuple[bool, str]:
    bad = [c["call_id"] for c in calls if c["action"] == "ir_backtest" and _failed(c)
           and any(t in c["text"] for t in PARAM_ERROR_TOKENS)]
    return not bad, f"{len(bad)} ir_backtest request errors {bad}"


def check_2(calls: list[dict]) -> tuple[bool, str]:
    def structural(c: dict) -> bool:
        p = c["payload"] if isinstance(c["payload"], dict) else {}
        r = p.get("result") if isinstance(p.get("result"), dict) else {}
        return r.get("source") == "local" or p.get("code") in STRUCTURE_CODES or any(k in c["text"] for k in STRUCTURE_CODES)

    bad = [c["call_id"] for c in calls if c["action"] == "ir_validate" and _failed(c) and structural(c)]
    return len(bad) <= 1, f"{len(bad)} structural ir_validate failures (limit 1) {bad}"


def check_3(calls: list[dict]) -> tuple[bool, str]:
    versions: set[str] = set()
    problems = []
    n = 0
    for c in calls:
        if c["action"] != "ir_backtest" or not _ok(c):
            continue
        n += 1
        p = c["payload"]
        r = p.get("result") if isinstance(p.get("result"), dict) else {}
        if r.get("strategy_id"):
            versions.add(r["strategy_id"])
        if not isinstance(p.get("evidence_dir"), str):
            problems.append(f"{c['call_id']}: no evidence_dir")
        card = _json(Path(str(r.get("run_card"))).read_text(encoding="utf-8")) if r.get("run_card") and Path(str(r["run_card"])).is_file() else None
        count = ((card or {}).get("trials") or {}).get("count")
        if count != len(versions):
            problems.append(f"{c['call_id']}: trials.count {count!r} != {len(versions)} versions")
    return n > 0 and not problems, f"{n} successful ir_backtest; " + ("; ".join(problems) or "all consistent")


def check_4(answer: str | None, runs: list[dict]) -> tuple[bool, str]:
    if not answer:
        return False, "no final answer"
    start = max(answer.rfind(t) for t in CARD_TITLES)
    if start < 0:
        return False, "the final answer has no result card"
    card = answer[start:].rstrip().splitlines()
    if not card[-1].startswith(CARD_LAST):
        return False, f"the answer does not end with the card (last line {card[-1][:60]!r})"
    m = next((re.search(r"(\d+) (?:个版本|versions) / (\d+) (?:次回测|backtests)", ln) for ln in card
              if re.search(r"(?:个版本|versions) / ", ln)), None)
    versions = {(rc.get("metrics") or {}).get("strategy_id") for rc in runs} - {None}
    if m is None or (int(m.group(1)), int(m.group(2))) != (len(versions), len(runs)):
        return False, (f"card header {m.group(0) if m else 'missing'} != {len(versions)} versions / {len(runs)} backtests "
                       "in the ledger")
    rows = [ln for ln in card if ln.startswith("| ") and not ln.startswith(("| 版本", "| Version"))]
    from src.tools.alphakeel_research_ledger import fmt_amount, fmt_fraction

    bad = []
    for row in rows:
        cells = [x.strip() for x in row.strip().strip("|").split("|")]
        if len(cells) < 6:
            bad.append(row)
            continue
        name, _, trades, net, dd = cells[:5]
        if not any(((rc.get("metrics") or {}).get("name") or (rc.get("metrics") or {}).get("strategy_id")) == name
                   and str((rc.get("metrics") or {}).get("trade_count")) == trades
                   and fmt_amount((rc.get("metrics") or {}).get("net_usdt")) == net
                   and fmt_fraction((rc.get("metrics") or {}).get("max_drawdown")) == dd for rc in runs):
            bad.append(row)
    return bool(rows) and not bad, f"{len(rows)} card rows; not in the registered metrics: {bad}"


def check_5(entries: list[dict], runs: list[dict], session_dir: Path | None) -> tuple[bool, str]:
    values: list[Any] = []
    for rc in runs:
        values += [v for v in (rc.get("metrics") or {}).values() if _dec(v) is not None]
    if session_dir is not None:
        for csv in (session_dir / "ir_runs").glob("*/artifacts/metrics.csv"):
            lines = csv.read_text(encoding="utf-8").splitlines()
            if len(lines) >= 2:
                values += [x for x in lines[1].split(",") if _dec(x) is not None]
    bad = []
    for e in entries:
        if e.get("type") != "answer_rejected":
            continue
        for issue in e.get("issues") or []:
            if not isinstance(issue, dict) or issue.get("value") is None:
                continue
            refs = " ".join(str(x) for x in (issue.get("source_tool_call_ids") or [])) + " " + str(issue.get("message") or "")
            if "ir_runs/" in refs and any(_matches(str(issue["value"]), v) for v in values):
                bad.append(f"{issue['value']} ({issue.get('reason')})")
    return not bad, f"{len(bad)} rejected registered figures {bad}"


def check_6(calls: list[dict]) -> tuple[bool, str]:
    n = sum(1 for c in calls if c["action"] == "freeze")
    return n == 0, f"{n} freeze calls"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("session_id")
    ap.add_argument("--sessions-dir", type=Path)
    ap.add_argument("--runs-dir", type=Path)
    ap.add_argument("--hypotheses", type=Path, help="hypotheses.json (default: the registry's default path)")
    a = ap.parse_args(argv)
    root = _default_root()
    trace_dir = (a.sessions_dir or root / "sessions") / a.session_id
    entries = load_trace(trace_dir)
    calls = research_calls(entries, trace_dir)
    sdir = session_run_dir(calls, a.session_id, a.runs_dir or root / "runs")
    runs = registered(sdir, a.hypotheses)
    results = [("1", "ir_backtest request errors = 0", *check_1(calls)),
               ("2", "structural ir_validate failures <= 1", *check_2(calls)),
               ("3", "evidence_dir and trials.count per ir_backtest", *check_3(calls)),
               ("4", "final answer ends with the result card, numbers registered", *check_4(final_answer(entries, trace_dir), runs)),
               ("5", "no rejected registered ir_runs figure", *check_5(entries, runs, sdir)),
               ("6", "no separate freeze", *check_6(calls))]
    print(f"session {a.session_id}: trace {trace_dir}, session run dir {sdir}, {len(runs)} registered runs")
    for n, title, ok, detail in results:
        print(f"{'PASS' if ok else 'FAIL'} {n} {title}: {detail}")
    return 0 if all(r[2] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
